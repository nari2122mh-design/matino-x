#!/usr/bin/env python3
"""Generate a Swift localization table compiled into the MATINO X executable.

The .lproj folders stay in the repository for editing, but the app reads the
generated Swift table at runtime, so the installed .app bundle does not need
separate .lproj folders. This is packaging only, not secrecy: Base64 is fully
reversible.
"""
from __future__ import annotations

import argparse
import base64
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE_DIR = ROOT / "ThreeOneOSFive"
OUTPUT = SOURCE_DIR / "helpers" / "EmbeddedLocalizations.generated.swift"
LOCALES = ("en", "vi", "zh-Hans")
ENTRY = re.compile(r'^\s*("(?:\\.|[^"\\])*")\s*=\s*("(?:\\.|[^"\\])*")\s*;\s*$')
CHUNK_SIZE = 96

_ESCAPES = {
    "n": "\n",
    "r": "\r",
    "t": "\t",
    '"': '"',
    "\\": "\\",
    "'": "'",
    "a": "\a",
    "b": "\b",
    "f": "\f",
    "v": "\v",
    "0": "\0",
}


def decode_string(literal: str) -> str:
    """Decode a quoted .strings literal (C-style escapes, not JSON)."""
    body = literal[1:-1]
    out: list[str] = []
    index = 0
    while index < len(body):
        char = body[index]
        if char != "\\":
            out.append(char)
            index += 1
            continue
        index += 1
        if index >= len(body):
            raise ValueError("Dangling escape at end of string literal")
        escape = body[index]
        if escape == "u" or escape == "U":
            if index + 4 >= len(body) + 1:
                raise ValueError("Truncated unicode escape")
            hex_digits = body[index + 1 : index + 5]
            out.append(chr(int(hex_digits, 16)))
            index += 5
            continue
        if escape in _ESCAPES:
            out.append(_ESCAPES[escape])
            index += 1
            continue
        if escape.isdigit():
            digits = ""
            while index < len(body) and body[index].isdigit() and len(digits) < 3:
                digits += body[index]
                index += 1
            out.append(chr(int(digits, 8)))
            continue
        out.append(escape)
        index += 1
    return "".join(out)


def read_strings(path: Path) -> dict[str, str]:
    values: dict[str, str] = {}
    text = path.read_text(encoding="utf-8-sig")
    # Strip block comments before line parsing.
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    for line_number, line in enumerate(text.splitlines(), 1):
        stripped = line.strip()
        if not stripped or stripped.startswith("//"):
            continue
        match = ENTRY.match(line)
        if not match:
            raise ValueError(f"Unsupported .strings syntax at {path}:{line_number}: {stripped[:80]}")
        key = decode_string(match.group(1))
        value = decode_string(match.group(2))
        if key in values:
            raise ValueError(f"Duplicate localization key {key!r} at {path}:{line_number}")
        values[key] = value
    if not values:
        raise ValueError(f"No localization entries found in {path}")
    return values


def render() -> str:
    tables: dict[str, dict[str, str]] = {}
    for locale in LOCALES:
        path = SOURCE_DIR / f"{locale}.lproj" / "Localizable.strings"
        tables[locale] = read_strings(path)

    lines = [
        "// Generated by generate_embedded_localizations.py; do not edit by hand.",
        "// Localization strings are compiled into the executable so the app bundle",
        "// does not ship separate .lproj folders. Base64 is not encryption.",
        "import Foundation",
        "",
        "enum EmbeddedLocalizationCatalog {",
        "    private static let encodedTables: [String: String] = [",
    ]
    for locale, table in tables.items():
        payload = json.dumps(table, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
        encoded = base64.b64encode(payload).decode("ascii")
        lines.append(f'        "{locale}": """')
        for start in range(0, len(encoded), CHUNK_SIZE):
            lines.append("        " + encoded[start : start + CHUNK_SIZE])
        lines.append('        """,')
    lines.extend(
        [
            "    ]",
            "",
            "    private static let tables: [String: [String: String]] = {",
            "        var result: [String: [String: String]] = [:]",
            "        for (locale, encoded) in encodedTables {",
            "            let compact = encoded.filter { !$0.isWhitespace }",
            "            guard let data = Data(base64Encoded: compact),",
            "                  let object = try? JSONSerialization.jsonObject(with: data),",
            "                  let table = object as? [String: String] else {",
            "                continue",
            "            }",
            "            result[locale] = table",
            "        }",
            "        return result",
            "    }()",
            "",
            "    static func text(for key: String, languageCode: String) -> String? {",
            "        tables[languageCode]?[key]",
            "    }",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the generated Swift is up to date")
    args = parser.parse_args()
    try:
        generated = render()
    except (OSError, ValueError) as error:
        print(f"Localization generation failed: {error}", file=sys.stderr)
        return 1

    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != generated:
            print(f"Generated localization file is stale: {OUTPUT}", file=sys.stderr)
            return 1
        print(f"Embedded localization table is up to date: {OUTPUT.relative_to(ROOT)}")
        return 0

    OUTPUT.write_text(generated, encoding="utf-8")
    print(f"Generated embedded localization table: {OUTPUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
